import { describe, expect, it } from 'vitest';
import { Capability, runS3ItemSummary, selectRequiredLocalProvider } from '@quoky/core';
import type { AiProvider, AiRequest } from '@quoky/core';
import type { CliRunner } from '@quoky/ai-cli';
import { selectionFixture } from '../provider-selection/test-support';
import { LONG_ITEM_PROVIDER_ID, composeLongItems, createLocalModelGate, gatedProvider } from './long-item-composition';

/**
 * ADR-0124 Part L C5a-2 at the composition root: the long-item provider (SUMMARIZATION only, always pinned, eligible ONLY
 * under `requiredLocality: 'LOCAL'`), the fresh probe, the shared single-in-flight gate, and nothing at all while the flag
 * is off. Fake runners and fake providers only: nothing is spawned, pulled or sent.
 */

const PIN = ['0a1b', '2c3d', '4e5f'].join('');
const OTHER_PIN = ['9f8e', '7d6c', '5b4a'].join('');
const MODEL = 'notes-model:8b';
const BLOB = `/home/owner/.ollama/models/blobs/sha256-${'0123456789abcdef'.repeat(4)}`;
const SHOW = ['  Model', '    architecture    qwen3', '    parameters      8.2B', '', '  Capabilities', '    completion', ''].join('\n');

function daemon(listedId: string): { runner: CliRunner; calls: string[][] } {
  const calls: string[][] = [];
  const runner: CliRunner = async (_bin, args) => {
    calls.push([...args]);
    const stdout = args[0] === 'list'
      ? `NAME ID SIZE MODIFIED\n${MODEL} ${listedId} 5.2 GB now\n`
      : args[1] === '--modelfile'
        ? `# Modelfile generated by "ollama show"\nFROM ${BLOB}\n`
        : args[0] === 'show'
          ? SHOW
          : '- a note line';
    return { code: 0, stdout, stderr: '', timedOut: false } as never;
  };
  return { runner, calls };
}

const ON = { mode: 'on' as const, model: { name: MODEL, digest: PIN } };

function embedding(id = 'embed-fake'): AiProvider & { calls: number } {
  const provider = {
    id,
    calls: 0,
    capabilities: [{ capability: Capability.EMBEDDING, priority: 10 }],
    executionLocality: 'LOCAL' as const,
    isAvailable: async () => true,
    execute: async () => {
      provider.calls += 1;
      return { text: '[]' };
    },
  };
  return provider;
}

describe('composeLongItems: off and shadow change nothing', () => {
  it('off: no provider, no gate, no wrapping, no runtime option, handlers unchanged', () => {
    const composed = composeLongItems({ chunkItems: { mode: 'off' }, ollamaBin: 'ollama' });
    const extra = [embedding()];
    const after = composed.providersAfterChat(extra);
    expect(after).toHaveLength(1);
    expect(after[0]).toBe(extra[0]);
    expect([composed.provider, composed.gate, composed.uncached, composed.runtimeOption(async () => undefined)]).toEqual([undefined, undefined, undefined, undefined]);
    expect(composed.handlersEnabled).toBe(false);
  });

  it('off (no new env): the provider set and the routing are byte-identical to a composition without it', async () => {
    const extra = [embedding()];
    const today = selectionFixture({ extra });
    const composed = composeLongItems({ chunkItems: { mode: 'off' }, ollamaBin: 'ollama' });
    const withFlag = selectionFixture({ extra: composed.providersAfterChat(extra) });
    expect(withFlag.catalog.providers.map((provider) => provider.id)).toEqual(today.catalog.providers.map((provider) => provider.id));
    for (const capability of [Capability.GENERAL_CHAT, Capability.SUMMARIZATION, Capability.CODE_IMPLEMENTATION, Capability.EMBEDDING]) {
      expect((await withFlag.router.select(capability)).id, capability).toBe((await today.router.select(capability)).id);
      expect(await withFlag.service.preferenceFor(capability, {})).toEqual(await today.service.preferenceFor(capability, {}));
    }
  });

  it('shadow: handlers attach the item, the runtime gets shadow with a pass-through gate, no provider is registered', async () => {
    const composed = composeLongItems({ chunkItems: { mode: 'shadow' }, ollamaBin: 'ollama' });
    const extra = [embedding()];
    expect(composed.handlersEnabled).toBe(true);
    expect(composed.provider).toBeUndefined();
    expect(composed.providersAfterChat(extra)[0]).toBe(extra[0]);
    const option = composed.runtimeOption(async () => undefined);
    expect(option?.mode).toBe('shadow');
    expect(await option?.exclusive(async () => 7)).toBe(7);
  });
});

describe('composeLongItems: on', () => {
  it('registers ONE SUMMARIZATION-only LOCAL provider under its own key, always pinned (a different ID is not ready)', async () => {
    const pinned = daemon(PIN);
    const composed = composeLongItems({ chunkItems: ON, ollamaBin: 'ollama', runner: pinned.runner });
    const provider = composed.provider as AiProvider;
    expect(provider.id).toBe(LONG_ITEM_PROVIDER_ID);
    expect(provider.capabilities.map((descriptor) => descriptor.capability)).toEqual([Capability.SUMMARIZATION]);
    expect(provider.executionLocality).toBe('LOCAL');
    expect(await provider.isAvailable()).toBe(true);
    expect(pinned.calls.map((args) => args.join(' '))).toEqual(['list', `show ${MODEL}`, `show --modelfile ${MODEL}`]);
    const swapped = daemon(OTHER_PIN);
    expect(await composeLongItems({ chunkItems: ON, ollamaBin: 'ollama', runner: swapped.runner }).provider?.isAvailable()).toBe(false);
    // Any other capability is refused before a spawn.
    const before = pinned.calls.length;
    await expect(provider.execute({ capability: Capability.GENERAL_CHAT, prompt: 'x' })).rejects.toThrow();
    expect(pinned.calls.length).toBe(before);
    expect(composed.uncached?.(provider)).toBe(true);
    expect(composed.runtimeOption(async () => undefined)?.exclusive).toBe(composed.gate);
  });

  function onFixture(env: Readonly<Record<string, string>> = {}, ready = true) {
    const composed = composeLongItems({ chunkItems: ON, ollamaBin: 'ollama', runner: daemon(PIN).runner });
    const long = composed.provider as AiProvider;
    const fixture = selectionFixture({
      env,
      present: ['ollama'],
      extra: composed.providersAfterChat([]),
      longItemKey: long.id,
      ...(composed.uncached !== undefined ? { uncached: composed.uncached } : {}),
    });
    fixture.ready.set(long.id, ready);
    return { composed, long, fixture };
  }

  it('unconstrained requests never select it; a constrained SUMMARIZATION request selects only it', async () => {
    // The owner's chat runs on a LOCAL Ollama model here, the strongest case for a wrong local pick.
    const { long, fixture } = onFixture({ QUOKY_OLLAMA_ENABLED: 'true', OLLAMA_MODEL: 'llama3.1', QUOKY_CHAT_PROVIDER: 'ollama' });
    for (const capability of [Capability.GENERAL_CHAT, Capability.SUMMARIZATION, Capability.DOCUMENT_ANALYSIS, Capability.READONLY_LOOKUP, Capability.CODE_IMPLEMENTATION]) {
      const preference = await fixture.service.preferenceFor(capability, {});
      expect(preference?.eligible ?? [], capability).not.toContain(long.id);
      expect((await fixture.router.select(capability)).id, capability).not.toBe(long.id);
      expect(fixture.service.isEligible(capability, {}, long.id), capability).toBe(false);
    }
    // Even with every other provider not ready, an unconstrained summary never falls back to it.
    for (const provider of fixture.catalog.providers) if (provider.id !== long.id) fixture.ready.set(provider.id, false);
    await expect(fixture.router.select(Capability.SUMMARIZATION)).rejects.toThrow();
    for (const provider of fixture.catalog.providers) fixture.ready.delete(provider.id);

    const constrained = await selectRequiredLocalProvider(fixture.router, Capability.SUMMARIZATION, {});
    expect(constrained.kind === 'selected' ? constrained.provider.id : constrained.kind).toBe(long.id);
    expect(await fixture.service.preferenceFor(Capability.SUMMARIZATION, { requiredLocality: 'LOCAL' })).toEqual({ eligible: [long.id], order: 'listed' });
    expect(fixture.service.isEligible(Capability.SUMMARIZATION, { requiredLocality: 'LOCAL' }, long.id)).toBe(true);
    // The existing LOCAL chat registration (llama3.1) is never in the constrained set.
    expect(fixture.catalog.ollama?.executionLocality).toBe('LOCAL');
    expect(fixture.service.isEligible(Capability.SUMMARIZATION, { requiredLocality: 'LOCAL' }, fixture.catalog.ollama?.id as string)).toBe(false);
    // No other capability may run under the constraint.
    for (const capability of [Capability.GENERAL_CHAT, Capability.CODE_IMPLEMENTATION, Capability.EMBEDDING]) {
      expect(await fixture.service.preferenceFor(capability, { requiredLocality: 'LOCAL' })).toEqual({ eligible: [], order: 'listed' });
      expect(await selectRequiredLocalProvider(fixture.router, capability, {})).toEqual({ kind: 'not-ready' });
    }
  });

  it('not ready: a constrained summary is not-ready, never another local model (no fallback candidate)', async () => {
    const { fixture } = onFixture({ QUOKY_OLLAMA_ENABLED: 'true', OLLAMA_MODEL: 'llama3.1', QUOKY_CHAT_PROVIDER: 'ollama' }, false);
    expect(await selectRequiredLocalProvider(fixture.router, Capability.SUMMARIZATION, {})).toEqual({ kind: 'not-ready' });
    expect(fixture.executed).toEqual([]);
  });

  it('it is never in the 모델 변경 list and never what a chat choice resolves to', async () => {
    const { long, fixture } = onFixture({ QUOKY_OLLAMA_ENABLED: 'true', OLLAMA_MODEL: 'llama3.1' });
    fixture.inventory = { status: 'OK', models: [MODEL, 'llama3.1:latest'] };
    const options = await fixture.service.options();
    for (const option of options) {
      expect(option.token).not.toBe(long.id);
      if (option.tier === 'chat') {
        const [provider, ...rest] = option.token.split(':');
        const resolved = fixture.catalog.resolveChat({ provider: provider as never, ...(rest.length > 0 ? { model: rest.join(':') } : {}) });
        expect(resolved?.id, option.token).not.toBe(long.id);
      }
    }
    expect(options.some((option) => option.token === `ollama:${MODEL}`)).toBe(true);
  });

  it('fresh probe: every constrained selection probes the long-item provider again (no cached readiness)', async () => {
    const { long, fixture } = onFixture();
    let probes = 0;
    const isAvailable = long.isAvailable.bind(long);
    Object.assign(long, { isAvailable: async () => { probes += 1; return isAvailable(); } });
    for (let round = 0; round < 3; round += 1) await selectRequiredLocalProvider(fixture.router, Capability.SUMMARIZATION, {});
    expect(probes).toBe(3);
  });
});

describe('the single-in-flight gate (RQ-3 T3-5)', () => {
  const NOTE = '- The part lists the plan items.';
  const prepared = Array.from({ length: 12 }, (_, index) => `Section ${index}. ${'Plain words for a long item. '.repeat(25)}`).join('\n\n');

  it('two concurrent S3 runs never overlap local calls, and embedding calls wait their turn', async () => {
    const gate = createLocalModelGate();
    let inFlight = 0;
    let maxInFlight = 0;
    const order: string[] = [];
    const tick = () => new Promise<void>((resolve) => setTimeout(resolve, 2));
    const track = async <T>(label: string, work: () => T): Promise<T> => {
      inFlight += 1;
      maxInFlight = Math.max(maxInFlight, inFlight);
      order.push(label);
      await tick();
      inFlight -= 1;
      return work();
    };
    const local: AiProvider = {
      id: LONG_ITEM_PROVIDER_ID,
      capabilities: [{ capability: Capability.SUMMARIZATION, priority: 10 }],
      executionLocality: 'LOCAL',
      isAvailable: async () => true,
      execute: (request: AiRequest) => track('s3', () => ({ text: request.prompt.includes('[Part ') ? 'Final summary line.' : NOTE })),
    };
    const embed = gatedProvider(
      {
        id: 'embed-fake',
        capabilities: [{ capability: Capability.EMBEDDING, priority: 10 }],
        executionLocality: 'LOCAL',
        isAvailable: async () => true,
        execute: () => track('embed', () => ({ text: '[]' })),
      },
      gate,
    );
    const selector = { select: async () => local };
    const run = () =>
      runS3ItemSummary(
        { mode: 'on', source: 'mail', title: 'Plan', author: 'Team', date: '2026-11-09T00:00:00.000Z', prepared, requestText: 'summarize this mail', language: 'en' },
        { selector, now: () => 0, exclusive: gate },
      );
    const results = await Promise.all([run(), run(), embed.execute({ capability: Capability.EMBEDDING, prompt: 'q' }), embed.execute({ capability: Capability.EMBEDDING, prompt: 'r' })]);
    expect(results[0].kind).toBe('summary');
    expect(results[1].kind).toBe('summary');
    expect(maxInFlight).toBe(1);
    expect(order.filter((label) => label === 'embed')).toHaveLength(2);
    expect(order.filter((label) => label === 's3').length).toBeGreaterThan(4);
  });

  it('on: the embedding provider is wrapped with the same gate; a call abandoned while waiting is not run', async () => {
    const composed = composeLongItems({ chunkItems: ON, ollamaBin: 'ollama', runner: daemon(PIN).runner });
    const inner = embedding();
    const [wrapped] = composed.providersAfterChat([inner]);
    expect(wrapped).not.toBe(inner);
    expect([wrapped?.id, wrapped?.executionLocality, wrapped?.capabilities]).toEqual([inner.id, 'LOCAL', inner.capabilities]);
    let release: () => void = () => undefined;
    const holding = new Promise<void>((resolve) => {
      release = resolve;
    });
    const held = (composed.gate as NonNullable<typeof composed.gate>)(() => holding);
    const abandoned = new AbortController();
    const waiting = wrapped?.execute({ capability: Capability.EMBEDDING, prompt: 'q', signal: abandoned.signal });
    abandoned.abort();
    release();
    await held;
    await expect(waiting).rejects.toThrow();
    expect(inner.calls).toBe(0);
    await wrapped?.execute({ capability: Capability.EMBEDDING, prompt: 'q' });
    expect(inner.calls).toBe(1);
  });
});
