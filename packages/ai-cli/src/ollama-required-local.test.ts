import { describe, expect, it } from 'vitest';
import { AiFailureKind, AiProviderManager, Capability, CapabilityRouter, selectRequiredLocalProvider } from '@quoky/core';
import type { CliRunner, CliRunOptions } from './cli-runner';
import { OllamaCliProvider, ollamaModelfileFromLocalBlob, ollamaShowIsLocalModel } from './index';

/**
 * ADR-0124 Part L C5a: a cloud-served Ollama model is refused under `requiredLocality: 'LOCAL'`. Core reads only the
 * declared locality; the name rule (`cloud` in the name or tag, ADR-0107 D6) stays here in the adapter. Nothing is spawned:
 * a refused provider is never probed.
 */
describe('Ollama under requiredLocality LOCAL', () => {
  it('a cloud-named model is never probed or selected; a local-named one is', async () => {
    const spawned: string[][] = [];
    const runner: CliRunner = async (_bin, args) => {
      spawned.push(args);
      return { stdout: '', stderr: '', exitCode: 0 } as never;
    };
    for (const model of ['gpt-oss:120b-cloud', 'qwen3-coder:cloud', 'Model-Cloud:latest']) {
      const cloud = new OllamaCliProvider({ model, runner });
      const router = new CapabilityRouter(new AiProviderManager([cloud]));
      expect(await selectRequiredLocalProvider(router, Capability.SUMMARIZATION), model).toEqual({ kind: 'not-ready' });
    }
    expect(spawned).toEqual([]);
    // A local-named model is a candidate: the router probes it (the cloud-named one beside it is still never probed).
    const local = new OllamaCliProvider({ model: 'qwen3:8b', runner });
    const cloud = new OllamaCliProvider({ model: 'qwen3:8b-cloud', providerId: 'ollama-cloud', runner });
    expect(local.executionLocality).toBe('LOCAL');
    await selectRequiredLocalProvider(new CapabilityRouter(new AiProviderManager([cloud, local])), Capability.SUMMARIZATION);
    expect(spawned.length).toBeGreaterThan(0);
  });
});

/**
 * ADR-0124 Part L C5a review round 2 (Codex P1, CA P2): the real cloud-alias control. With `localWeights`, readiness needs
 * positive local evidence from the daemon's metadata; every probe error is not ready. Fake runner only: nothing is pulled,
 * no model runs, no input is sent.
 */
describe('Ollama local-weights readiness (requiredLocality LOCAL)', () => {
  const MODEL = 'team-notes:8b';
  const DIGEST = ['ab12', 'cd34', 'ef56'].join('');
  const BLOB = `/home/owner/.ollama/models/blobs/sha256-${'0123456789abcdef'.repeat(4)}`;
  const LIST = `NAME ID SIZE MODIFIED\n${MODEL} ${DIGEST} 4.9 GB now\n`;
  const LOCAL_SHOW = ['  Model', '    architecture    gemma3', '    parameters      4.3B', '    quantization    Q4_K_M', '', '  Capabilities', '    completion', ''].join('\n');
  const REMOTE_SHOW = ['  Model', '    Remote model    big-model:latest', '    Remote URL      https://remote.example.invalid', '    architecture    gemma3', '', '  Capabilities', '    completion', ''].join('\n');
  const LOCAL_MODELFILE = `# Modelfile generated by "ollama show"\nFROM ${BLOB}\nPARAMETER temperature 1\n`;
  const ALIAS_MODELFILE = '# Modelfile generated by "ollama show"\nFROM big-model:cloud\n';

  type Answer = { code?: number; stdout?: string; timedOut?: boolean; throws?: boolean };
  function fake(answers: { list?: Answer; show?: Answer; modelfile?: Answer }) {
    const calls: { args: string[]; options: CliRunOptions }[] = [];
    const runner: CliRunner = async (_bin, args, options) => {
      calls.push({ args: [...args], options });
      const key = args[0] === 'list' ? 'list' : args[1] === '--modelfile' ? 'modelfile' : args[0] === 'show' ? 'show' : 'other';
      const defaults: Record<string, Answer> = { list: { stdout: LIST }, show: { stdout: LOCAL_SHOW }, modelfile: { stdout: LOCAL_MODELFILE }, other: { stdout: 'note' } };
      const answer = (answers as Record<string, Answer | undefined>)[key] ?? defaults[key] as Answer;
      if (answer.throws === true) throw new Error('spawn');
      return { code: answer.code ?? 0, stdout: answer.stdout ?? '', stderr: '', timedOut: answer.timedOut ?? false } as never;
    };
    return { runner, calls };
  }

  it('a normal local model (local blob, no remote fields) is available; only read-only metadata probes, no input', async () => {
    const env = fake({});
    expect(await new OllamaCliProvider({ model: MODEL, runner: env.runner, localWeights: {} }).isAvailable()).toBe(true);
    expect(env.calls.map((call) => call.args)).toEqual([['list'], ['show', MODEL], ['show', '--modelfile', MODEL]]);
    for (const call of env.calls) expect(call.options.input).toBe('');
  });

  it('remote fields in `ollama show` are not available (a local alias of a cloud model)', async () => {
    const env = fake({ show: { stdout: REMOTE_SHOW } });
    expect(await new OllamaCliProvider({ model: MODEL, runner: env.runner, localWeights: {} }).isAvailable()).toBe(false);
    const snake = fake({ show: { stdout: '{"remote_model":"big-model","remote_host":"https://remote.example.invalid"}\n' } });
    expect(await new OllamaCliProvider({ model: MODEL, runner: snake.runner, localWeights: {} }).isAvailable()).toBe(false);
  });

  it('a Modelfile whose FROM is not a local weights blob is not available (positive evidence required)', async () => {
    for (const modelfile of [ALIAS_MODELFILE, '# no FROM line\n', `FROM ${BLOB}\nFROM big-model:cloud\n`, 'FROM relative/sha256-' + 'f'.repeat(64) + '\n']) {
      const env = fake({ modelfile: { stdout: modelfile } });
      expect(await new OllamaCliProvider({ model: MODEL, runner: env.runner, localWeights: {} }).isAvailable(), modelfile).toBe(false);
    }
  });

  it('a pinned digest must equal the `ollama list` ID: a mismatch is not available, a match is', async () => {
    const env = fake({});
    expect(await new OllamaCliProvider({ model: MODEL, runner: env.runner, localWeights: { pinnedDigest: 'f'.repeat(12) } }).isAvailable()).toBe(false);
    expect(env.calls.map((call) => call.args)).toEqual([['list']]);
    expect(await new OllamaCliProvider({ model: MODEL, runner: env.runner, localWeights: { pinnedDigest: DIGEST } }).isAvailable()).toBe(true);
    expect(() => new OllamaCliProvider({ model: MODEL, runner: env.runner, localWeights: { pinnedDigest: 'not-a-digest' } })).toThrow(TypeError);
  });

  it.each<[string, { list?: Answer; show?: Answer; modelfile?: Answer }]>([
    ['show throws', { show: { throws: true } }],
    ['show exits non-zero', { show: { code: 1 } }],
    ['show times out', { show: { timedOut: true } }],
    ['modelfile throws', { modelfile: { throws: true } }],
    ['modelfile exits non-zero', { modelfile: { code: 1 } }],
    ['modelfile times out', { modelfile: { timedOut: true } }],
    ['list times out (fail closed, not indeterminate)', { list: { timedOut: true } }],
    ['list throws', { list: { throws: true } }],
  ])('a probe error is not available: %s', async (_name, answers) => {
    const env = fake(answers);
    expect(await new OllamaCliProvider({ model: MODEL, runner: env.runner, localWeights: {} }).isAvailable()).toBe(false);
  });

  it('without localWeights readiness is today\'s: one `ollama list`, no show', async () => {
    const env = fake({ show: { stdout: REMOTE_SHOW } });
    expect(await new OllamaCliProvider({ model: MODEL, runner: env.runner }).isAvailable()).toBe(true);
    expect(env.calls.map((call) => call.args)).toEqual([['list']]);
  });

  it('under requiredLocality LOCAL a remote-backed alias is never selected and never receives input', async () => {
    const env = fake({ show: { stdout: REMOTE_SHOW } });
    const alias = new OllamaCliProvider({ model: MODEL, runner: env.runner, localWeights: {} });
    expect(alias.executionLocality).toBe('LOCAL');
    expect(await selectRequiredLocalProvider(new CapabilityRouter(new AiProviderManager([alias])), Capability.SUMMARIZATION)).toEqual({ kind: 'not-ready' });
    expect(env.calls.some((call) => call.args[0] === 'run')).toBe(false);
  });
});

/**
 * ADR-0124 Part L C5a review round 3 (Codex P2 ×2, CA P3-c): the daemon-metadata parsers accept only a recognized format
 * and refuse anything malformed. Pure functions over fixed strings; nothing is spawned.
 */
describe('Ollama local-weights parsers fail closed on unknown or malformed formats', () => {
  const HEX = '0123456789abcdef'.repeat(4);
  const BLOB = `/home/owner/.ollama/models/blobs/sha256-${HEX}`;
  const SHOW = ['  Model', '    architecture         gemma3', '    parameters           4.3B', '', '  Capabilities', '    completion', ''].join('\n');

  it('show: only the recognized table without remote fields is local', () => {
    expect(ollamaShowIsLocalModel(SHOW)).toBe(true);
    expect(ollamaShowIsLocalModel(SHOW.replace(/\n/gu, '\r\n'))).toBe(true);
    for (const output of [
      '',
      '{"model_info":{}}',
      '{"remoteModel":"big-model","remoteHost":"https://remote.example.invalid"}',
      '{"remote_model":"big-model"}',
      SHOW.replace('    parameters', '    Remote model    big-model:latest\n    parameters'),
      SHOW.replace('    parameters', '    remote_host    https://remote.example.invalid\n    parameters'),
      ['  Model', '    parameters    4.3B', ''].join('\n'),
      ['  Capabilities', '    architecture    gemma3', ''].join('\n'),
    ]) {
      expect(ollamaShowIsLocalModel(output), JSON.stringify(output)).toBe(false);
    }
  });

  it('modelfile: blob FROM lines with directives and """ blocks are local', () => {
    const modelfile = [
      '# Modelfile generated by "ollama show"',
      '# FROM some-model:latest',
      `FROM ${BLOB}`,
      `FROM ${BLOB.replace('0123', '4567')}`,
      'TEMPLATE """{{ .Prompt }}',
      'from a line inside the template',
      'FROM not-a-blob:latest',
      '{{ end }}"""',
      'PARAMETER stop <end_of_turn>',
      'SYSTEM """one line"""',
      'MESSAGE user """hello"""',
      'MESSAGE assistant """multi',
      'FROM not-a-blob:latest',
      'line"""',
      'MESSAGE user plain text',
      'LICENSE """Terms',
      `FROM ${BLOB}`,
      'end of terms"""',
      '',
    ].join('\n');
    expect(ollamaModelfileFromLocalBlob(modelfile)).toBe(true);
  });

  it('modelfile: malformed or non-blob directives are refused', () => {
    for (const modelfile of [
      '',
      '# only comments\n',
      `FROM ${BLOB}\nFROM\n`,
      `FROM ${BLOB}\nFROM big-model:cloud\n`,
      `FROM ${BLOB} extra\n`,
      `from ${BLOB}\n`,
      `  FROM ${BLOB}\n`,
      `FROM ${BLOB.replace('sha256-', 'sha256:')}\n`,
      `FROM relative/blobs/sha256-${HEX}\n`,
      `FROM ${BLOB}\nTEMPLATE """never closed\n`,
      `FROM ${BLOB}\nparameter temperature 1\n`,
      `FROM ${BLOB}\nPARAMETER\n`,
      'LICENSE """terms\n"""\n',
      `FROM ${BLOB}\nUNKNOWN value\n`,
      `FROM ${BLOB}\nSYSTEM """text""" trailing\n`,
      `FROM ${BLOB}\nSYSTEM """open\nclose""" trailing\n`,
      `FROM ${BLOB}\nSYSTEM """open\nclose""" again """\n`,
      `FROM ${BLOB}\nSYSTEM text """\n`,
      `FROM ${BLOB}\nMESSAGE user\n`,
      `FROM ${BLOB}\nMESSAGE user """hi""" trailing\n`,
    ]) {
      expect(ollamaModelfileFromLocalBlob(modelfile), JSON.stringify(modelfile)).toBe(false);
    }
  });
});

/** ADR-0124 Part L C5a-2: an abandoned S3 call kills the child (the runner's signal), it does not run to its timeout. */
describe('Ollama execute honours request.signal', () => {
  it('passes the request signal to the runner; no signal, no option', async () => {
    const seen: CliRunOptions[] = [];
    const runner: CliRunner = async (_bin, _args, options) => {
      seen.push(options);
      return { code: 0, stdout: 'note', stderr: '', timedOut: false } as never;
    };
    const provider = new OllamaCliProvider({ model: 'notes-model:8b', runner });
    const call = new AbortController();
    await provider.execute({ capability: Capability.SUMMARIZATION, prompt: 'p', timeoutMs: 1_000, signal: call.signal });
    expect(seen[0]?.signal).toBe(call.signal);
    await provider.execute({ capability: Capability.SUMMARIZATION, prompt: 'p', timeoutMs: 1_000 });
    expect('signal' in (seen[1] as object)).toBe(false);
  });

  it('an aborted call is a failure, never an answer (the runner reports no exit code)', async () => {
    const runner: CliRunner = async (_bin, _args, options) => {
      expect(options.signal?.aborted).toBe(true);
      return { code: null, stdout: '', stderr: '', timedOut: false } as never;
    };
    const provider = new OllamaCliProvider({ model: 'notes-model:8b', runner });
    const call = new AbortController();
    call.abort();
    // CH3 run 1: the caller's own bound, never UNAVAILABLE (which would make the router invalidate the provider).
    await expect(provider.execute({ capability: Capability.SUMMARIZATION, prompt: 'p', timeoutMs: 1_000, signal: call.signal })).rejects.toMatchObject({ kind: AiFailureKind.TIMEOUT });
  });

  it('without an aborted signal a run with no exit code is still UNAVAILABLE (today\'s classification)', async () => {
    const runner: CliRunner = async () => ({ code: null, stdout: '', stderr: 'spawn failed', timedOut: false }) as never;
    const provider = new OllamaCliProvider({ model: 'notes-model:8b', runner });
    await expect(provider.execute({ capability: Capability.SUMMARIZATION, prompt: 'p', timeoutMs: 1_000, signal: new AbortController().signal })).rejects.toMatchObject({ kind: AiFailureKind.UNAVAILABLE });
    await expect(provider.execute({ capability: Capability.SUMMARIZATION, prompt: 'p', timeoutMs: 1_000 })).rejects.toMatchObject({ kind: AiFailureKind.UNAVAILABLE });
  });
});

/**
 * ADR-0124 Part L C5a, CH3 run 1 (INVALID): 4/32 items ended `today (not-ready)` in 140-250 ms with no call, each right
 * after an item whose call the S3 per-call bound abandoned. The failure shape, reproduced with a fake runner: S3's deadline
 * aborts the call, the runner kills the child and reports no exit code (`code: null`, `timedOut: false`) a few hundred ms
 * later; S3 has already moved on and the next item's FRESH readiness probe is in flight. Classified UNAVAILABLE, the
 * router's `invalidate` bumped the provider's generation and the manager discarded that in-flight probe as not ready.
 */
describe('CH3 run 1: an abandoned call never spoils the next item\'s readiness probe', () => {
  const MODEL = 'notes-model:8b';
  const BLOB = `/home/owner/.ollama/models/blobs/sha256-${'0123456789abcdef'.repeat(4)}`;
  const SHOW = ['  Model', '    architecture    qwen3', '', '  Capabilities', '    completion', ''].join('\n');

  function deferred(): { promise: Promise<void>; release: () => void } {
    let release: () => void = () => undefined;
    const promise = new Promise<void>((resolve) => {
      release = resolve;
    });
    return { promise, release };
  }

  it('the abandoned call settles TIMEOUT while the next fresh probe is in flight, and that probe still selects the model', async () => {
    const teardown = deferred();
    let probeHold: { promise: Promise<void>; release: () => void } | undefined;
    const runner: CliRunner = async (_bin, args, options) => {
      if (args[0] === 'run') {
        // The child is killed on abort; its exit (no code) arrives only after the teardown.
        await new Promise<void>((resolve) => options.signal?.addEventListener('abort', () => resolve(), { once: true }));
        await teardown.promise;
        return { code: null, stdout: '', stderr: '', timedOut: false } as never;
      }
      if (args[0] === 'list' && probeHold !== undefined) await probeHold.promise;
      const stdout = args[0] === 'list' ? `NAME ID SIZE MODIFIED\n${MODEL} 0a1b2c3d4e5f 5.2 GB now\n`
        : args[1] === '--modelfile' ? `FROM ${BLOB}\n` : SHOW;
      return { code: 0, stdout, stderr: '', timedOut: false } as never;
    };
    const provider = new OllamaCliProvider({ model: MODEL, runner, localWeights: { pinnedDigest: '0a1b2c3d4e5f' }, noThinking: true });
    const router = new CapabilityRouter(new AiProviderManager([provider], { uncached: (candidate) => candidate === provider }));

    const first = await selectRequiredLocalProvider(router, Capability.SUMMARIZATION);
    if (first.kind !== 'selected') throw new Error('first selection not ready');
    const call = new AbortController();
    const abandoned = first.provider.execute({ capability: Capability.SUMMARIZATION, prompt: 'p', timeoutMs: 20_000, signal: call.signal });
    const outcome = abandoned.then(() => 'answered', (error: unknown) => (error as { kind?: string }).kind);
    call.abort(); // S3's per-call deadline fired; S3 moves on to the next item.

    probeHold = deferred();
    const next = selectRequiredLocalProvider(router, Capability.SUMMARIZATION); // the next item's fresh probe, in flight
    teardown.release(); // the killed child exits while that probe is running
    const kind = await outcome;
    probeHold.release();
    expect((await next).kind).toBe('selected');
    expect(kind).toBe(AiFailureKind.TIMEOUT);
  });

  it('a real UNAVAILABLE settling during the probe still makes that probe not ready (fail closed is kept)', async () => {
    let probeHold: { promise: Promise<void>; release: () => void } | undefined;
    let fail: () => void = () => undefined;
    const runner: CliRunner = async (_bin, args) => {
      if (args[0] === 'run') {
        await new Promise<void>((resolve) => {
          fail = resolve;
        });
        return { code: null, stdout: '', stderr: 'daemon gone', timedOut: false } as never;
      }
      if (args[0] === 'list' && probeHold !== undefined) await probeHold.promise;
      const stdout = args[0] === 'list' ? `NAME ID SIZE MODIFIED\n${MODEL} 0a1b2c3d4e5f 5.2 GB now\n`
        : args[1] === '--modelfile' ? `FROM ${BLOB}\n` : SHOW;
      return { code: 0, stdout, stderr: '', timedOut: false } as never;
    };
    const provider = new OllamaCliProvider({ model: MODEL, runner, localWeights: {}, noThinking: true });
    const router = new CapabilityRouter(new AiProviderManager([provider], { uncached: (candidate) => candidate === provider }));
    const first = await selectRequiredLocalProvider(router, Capability.SUMMARIZATION);
    if (first.kind !== 'selected') throw new Error('first selection not ready');
    const failed = first.provider.execute({ capability: Capability.SUMMARIZATION, prompt: 'p', timeoutMs: 20_000 }).then(() => 'answered', (error: unknown) => (error as { kind?: string }).kind);
    probeHold = deferred();
    const next = selectRequiredLocalProvider(router, Capability.SUMMARIZATION);
    await Promise.resolve();
    fail();
    expect(await failed).toBe(AiFailureKind.UNAVAILABLE);
    probeHold.release();
    expect(await next).toEqual({ kind: 'not-ready' });
  });
});

/**
 * ADR-0124 Part L C5a, CH3 run 1 (INVALID): qwen3:8b reasoned before it answered (`Thinking...` on stdout) and the first
 * map call of 28/32 items hit the 20 s bound. The long-item provider runs with reasoning off and hidden, and an output that
 * still starts with a reasoning block is a failed call. Every other Ollama provider's arguments and output are unchanged.
 */
describe('Ollama noThinking (the long-item provider only)', () => {
  const MODEL = 'notes-model:8b';

  function recording(stdout: string) {
    const args: string[][] = [];
    const runner: CliRunner = async (_bin, argv) => {
      args.push([...argv]);
      return { code: 0, stdout, stderr: '', timedOut: false } as never;
    };
    return { runner, args };
  }

  it('noThinking adds --think=false --hidethinking to `ollama run` (argv and audit); without it the args are byte-identical', async () => {
    const plain = recording('- a note');
    const today = new OllamaCliProvider({ model: MODEL, runner: plain.runner });
    expect(today.buildArgs()).toEqual(['run', '--nowordwrap', MODEL]);
    const todayResult = await today.execute({ capability: Capability.SUMMARIZATION, prompt: 'p' });
    expect(plain.args).toEqual([['run', '--nowordwrap', MODEL]]);
    expect(todayResult.audit?.sanitizedCommand).toEqual(['ollama', 'run', '--nowordwrap', MODEL]);

    const off = recording('- a note');
    const longItem = new OllamaCliProvider({ model: MODEL, runner: off.runner, noThinking: true });
    expect(longItem.buildArgs()).toEqual(['run', '--nowordwrap', '--think=false', '--hidethinking', MODEL]);
    const result = await longItem.execute({ capability: Capability.SUMMARIZATION, prompt: 'p' });
    expect(off.args).toEqual([['run', '--nowordwrap', '--think=false', '--hidethinking', MODEL]]);
    expect(result.audit?.sanitizedCommand).toEqual(['ollama', 'run', '--nowordwrap', '--think=false', '--hidethinking', MODEL]);
    expect(result.text).toBe('- a note');
  });

  it('an output that still starts with a reasoning block fails closed; the reasoning is never returned', async () => {
    for (const stdout of ['Thinking...\nSECRET-TRACE the user wants notes.\n...done thinking.\n\n- a note\n', '  <think>\nSECRET-TRACE\n</think>\n- a note', '\u001b[1mThinking...\u001b[0m\nSECRET-TRACE\n']) {
      const provider = new OllamaCliProvider({ model: MODEL, runner: recording(stdout).runner, noThinking: true });
      const error = await provider.execute({ capability: Capability.SUMMARIZATION, prompt: 'p' }).then(() => undefined, (caught: unknown) => caught as { kind?: string; message?: string });
      expect(error?.kind, stdout).toBe(AiFailureKind.EXECUTION_FAILED);
      expect(error?.message ?? '').not.toContain('SECRET-TRACE');
    }
    // A note that mentions thinking later is an answer.
    const ok = new OllamaCliProvider({ model: MODEL, runner: recording('- Thinking... about the budget (owner)').runner, noThinking: true });
    expect((await ok.execute({ capability: Capability.SUMMARIZATION, prompt: 'p' })).text).toBe('- Thinking... about the budget (owner)');
  });

  it('without noThinking the same output is today\'s answer (existing providers unchanged)', async () => {
    const stdout = 'Thinking...\nreasoning\n...done thinking.\n\n- a note';
    const result = await new OllamaCliProvider({ model: MODEL, runner: recording(stdout).runner }).execute({ capability: Capability.SUMMARIZATION, prompt: 'p' });
    expect(result.text).toBe(stdout);
  });
});
