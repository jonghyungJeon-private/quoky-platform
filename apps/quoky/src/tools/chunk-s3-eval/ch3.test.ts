/** A key point's value in a form the scorer reads back (the atom, not the sentence). */
function rendered(atom: string): string {
  if (atom.startsWith('num:')) return atom.slice(4);
  if (atom.startsWith('date:')) {
    const [month, day] = atom.slice(5).split('-');
    return `${Number(month)}/${Number(day)}`;
  }
  return atom.slice('name:'.length);
}

const ALL_KEYS = CASES.flatMap((c) => c.keyPoints);
const escaped = (text: string): string => JSON.stringify(text).slice(1, -1);
/** A faithful fake: it writes only key points whose sentence (map / today) or note (reduce) is in its input. */
function faithful(input: string): string {
  const lines = ALL_KEYS.filter((key) => input.includes(escaped(key.text)) || input.includes(escaped(`${key.subject}: ${rendered(key.atom)}`))).map((key) => `${key.subject}: ${rendered(key.atom)}`);
  return (lines.length === 0 ? ['nothing to note'] : lines.slice(0, 8)).join('\n');
}

function daemon(listedId: string, answer: (input: string) => string = faithful): { runner: CliRunner; runs: string[] } {
  const runs: string[] = [];
  const runner: CliRunner = async (_bin, args, options) => {
    const stdout = args[0] === 'list'
      ? `NAME ID SIZE MODIFIED\n${MODEL} ${listedId} 5.2 GB now\n`
      : args[1] === '--modelfile'
        ? `# Modelfile generated by "ollama show"\nFROM ${BLOB}\n`
        : args[0] === 'show'
          ? SHOW
          : (runs.push(options.input), answer(options.input));
    return { code: 0, stdout, stderr: '', timedOut: false } as never;
  };
  return { runner, runs };
}

function todayProvider(answer: (input: string) => string = faithful): AiProvider & { calls: number } {
  const provider = {
    id: 'claude-cli-fake',
    calls: 0,
    capabilities: [{ capability: Capability.SUMMARIZATION, priority: 10 }],
    isAvailable: async () => true,
    execute: async (request: { prompt: string }) => {
      provider.calls += 1;
      return { text: answer(request.prompt) };
    },
  };
  return provider as never;
}

