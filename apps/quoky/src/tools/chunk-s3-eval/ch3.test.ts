describe('chunk-s3-eval CLI', () => {
  function deps(overrides: Partial<S3CliDeps> = {}, listed = PIN) {
    const out: string[] = [];
    const err: string[] = [];
    const files = new Map<string, string>();
    const fake = daemon(listed);
    const today = todayProvider();
    let freeze: FreezeRecord | undefined = JSON.parse(readFileSync(CH3_FREEZE_PATH, 'utf8')) as FreezeRecord;
    const d: S3CliDeps = {
      stdout: (line) => out.push(line),
      stderr: (line) => err.push(line),
      now: () => new Date('2026-11-09T00:00:00.000Z'),
      clock: ticking(),
      corpus: () => CASES,
      readFreeze: () => freeze,
      writeFreeze: (record) => {
        freeze = record;
      },
      readFile: (path) => {
        const text = files.get(path);
        if (text === undefined) throw new Error(`no ${path}`);
        return text;
      },
      writeFile: (path, text) => void files.set(path, text),
      localArm: (options) => composeLocalArm({ ...options, runner: fake.runner }),
      todayProvider: () => today,
      rss: async () => undefined,
      rubric: () => loadRubricWording(),
      seed: 'cli-test-seed',
      ...overrides,
    };
    return { d, out, err, files, fake, today };
  }
  const planDigest = buildCh3Plan({ cases: CASES, corpusDigest: ch3CorpusDigest(CASES), local: LOCAL, today: TODAY }).digest;
  const runArgs = ['--mode', 'run', '--local-model', MODEL, '--local-digest', PIN, '--out', '/eval-out'];

  it('verify and plan make no model call; plan prints the digest and readiness', async () => {
    const t = deps();
    expect(await runCli(['--mode', 'verify'], t.d)).toBe(EXIT_OK);
    expect(await runCli(['--mode', 'plan', '--local-model', MODEL, '--local-digest', PIN], t.d)).toBe(EXIT_OK);
    expect(t.out.join('\n')).toContain(planDigest);
    expect(t.out.join('\n')).toMatch(/ready .*: yes/u);
    expect(t.fake.runs).toEqual([]);
    expect(t.today.calls).toBe(0);
  });

  it('refuses to run without a digest, with a stale digest, unpinned, on a cloud model, unready, or on a changed corpus; nothing is called', async () => {
    const cases: [readonly string[], Partial<S3CliDeps>, string][] = [
      [runArgs, {}, PIN],
      [[...runArgs, '--digest', 'ffffffffffffffff'], {}, PIN],
      [['--mode', 'run', '--local-model', MODEL, '--digest', planDigest], {}, PIN],
      [['--mode', 'run', '--local-model', 'big:70b-cloud', '--local-digest', PIN, '--digest', planDigest], {}, PIN],
      [[...runArgs, '--digest', planDigest], {}, OTHER_PIN],
      [[...runArgs, '--digest', planDigest], { corpus: () => CASES.slice(1) }, PIN],
    ];
    for (const [argv, overrides, listed] of cases) {
      const t = deps(overrides, listed);
      expect(await runCli(argv, t.d), argv.join(' ')).toBe(EXIT_BLOCKED);
      expect(t.fake.runs, argv.join(' ')).toEqual([]);
      expect(t.today.calls, argv.join(' ')).toBe(0);
      expect(t.files.size).toBe(0);
    }
  });

  it('a full run with fakes writes the content-free report, the blind sheet, its key and the items, then score-labels decides', async () => {
    const t = deps();
    const code = await runCli([...runArgs, '--digest', planDigest], t.d);
    expect([EXIT_NON_GATING, EXIT_FAILED]).toContain(code);
    expect(t.today.calls).toBe(CASES.length);
    const paths = [...t.files.keys()];
    const find = (suffix: string): string => paths.find((p) => p.endsWith(suffix)) as string;
    for (const suffix of ['.report.json', '.sheet.json', '.sheet.md', '.key.json', '.items.md']) expect(find(suffix), suffix).toBeDefined();
    const report = JSON.parse(t.files.get(find('.report.json')) as string);
    expect(report.planDigest).toBe(planDigest);
    expect(report.items).toHaveLength(CASES.length);
    expect(report.ch5.maxConcurrentLocalCalls).toBe(1);
    expect(report.ch5.peakRss.measured).toBe(false);
    expect(report.arms.S3.coverage).toBeGreaterThan(0);
    const sheetText = t.files.get(find('.sheet.json')) as string;
    expect(sheetText).not.toContain('cli-test-seed');

    // Unfilled: BLOCKED. Filled with a clear S3 preference: PASSED only if the run's coverage and invented checks passed.
    const args = ['--mode', 'score-labels', '--sheet', find('.sheet.json'), '--key', find('.key.json'), '--report', find('.report.json')];
    expect(await runCli(args, t.d)).toBe(EXIT_BLOCKED);
    const sheet = JSON.parse(sheetText) as BlindSheet;
    const key = JSON.parse(t.files.get(find('.key.json')) as string) as { sides: Record<string, { A: string }> };
    for (const entry of sheet.entries) {
      entry.labels = { A: 'good', B: 'usable' };
      entry.preference = key.sides[entry.caseId]?.A === 'S3' ? 'A' : 'B';
    }
    t.files.set(find('.sheet.json'), JSON.stringify(sheet));
    const scored = await runCli(args, t.d);
    expect(scored).toBe(report.status === 'NON-GATING' ? EXIT_OK : EXIT_FAILED);
    expect(t.out.join('\n')).toMatch(/preference: S3 preferred in 32 of 32/u);
  });
});
