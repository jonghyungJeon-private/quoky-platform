describe('CH3 scorer', () => {
  it('reads dates, times and numbers in the forms the arms write', () => {
    const atoms = valueAtoms('예산 3,450만 원, 12월 3일 마감, Dec 4 review, 2026-11-05, 14:30 call, 7/9 and 45%');
    for (const atom of ['num:3450', 'date:12-03', 'date:12-04', 'date:11-05', 'time:14:30', 'date:07-09', 'num:45']) expect(atoms.has(atom), atom).toBe(true);
    expect(atoms.has('num:2026')).toBe(false);
  });

  it('coverage counts planted atoms; an atom the source does not carry is invented', () => {
    const c = CASES[0] as Ch3Case;
    const source = valueAtoms(`${itemSourceText(c.item)}\n${c.item.requestText}`);
    const all = c.keyPoints.map((key) => `${key.subject}: ${rendered(key.atom)}`).join('\n');
    const full = scoreSummary(c, all, source);
    expect(full.covered).toBe(c.keyPoints.length);
    expect(full.valuePresent).toBe(c.keyPoints.length);
    expect(full.unanchored).toBe(0);
    expect(full.invented).toEqual([]);
    const invented = scoreSummary(c, `${all}\n총 98765건`, source);
    expect(invented.invented).toEqual(['num:98765']);
    expect(scoreSummary(c, '요약할 내용이 없습니다', source).covered).toBe(0);
  });

  it('a bare dump of the item values scores no coverage and is flagged; a value needs its own subject in the same unit', () => {
    for (const c of CASES) {
      const source = valueAtoms(`${itemSourceText(c.item)}\n${c.item.requestText}`);
      // Every planted value, as a list and as one sentence: present, never beside its subject.
      for (const dump of [c.keyPoints.map((key) => `- ${rendered(key.atom)}`).join('\n'), `Values: ${c.keyPoints.map((key) => rendered(key.atom)).join(', ')}.`]) {
        const score = scoreSummary(c, dump, source);
        expect(score.covered, c.item.id).toBe(0);
        expect(score.valuePresent, c.item.id).toBe(c.keyPoints.length);
        expect(score.unanchored, c.item.id).toBe(c.keyPoints.length);
      }
    }
    const c = CASES.find((x) => new Set(x.keyPoints.map((key) => key.subject)).size >= 2) as Ch3Case;
    const [first, second] = c.keyPoints.filter((key, at, all) => all.findIndex((k) => k.subject === key.subject) === at) as [Ch3Case['keyPoints'][number], Ch3Case['keyPoints'][number]];
    const source = valueAtoms(itemSourceText(c.item));
    // Subjects swapped across sentences: neither value is credited.
    expect(scoreSummary(c, `${second.subject} moved. Then ${rendered(first.atom)} was set.\n${first.subject}: ${rendered(second.atom)}`, source).covered).toBe(
      first.subject === second.subject ? 2 : 0,
    );
    expect(scoreSummary(c, `${first.subject}: ${rendered(first.atom)}. ${second.subject} is at ${rendered(second.atom)}.`, source).covered).toBe(2);
  });
});

describe('CH3 binomial test', () => {
  const exact = (k: number, n: number): number => {
    let tail = 0n;
    let choose = 1n;
    for (let i = 0; i <= n; i += 1) {
      if (i >= k) tail += choose;
      choose = (choose * BigInt(n - i)) / BigInt(i + 1);
    }
    return Number(tail) / 2 ** n;
  };
  it('is the exact one-sided tail P(X >= k) of Binomial(n, 1/2)', () => {
    for (const [k, n] of [[0, 25], [13, 25], [17, 25], [18, 25], [25, 25], [20, 30], [40, 60]] as const) expect(binomialOneSidedP(k, n)).toBeCloseTo(exact(k, n), 12);
    expect(binomialOneSidedP(18, 25)).toBeLessThan(0.05);
    expect(binomialOneSidedP(17, 25)).toBeGreaterThan(0.05);
    expect(binomialOneSidedP(0, 0)).toBe(1);
    expect(() => binomialOneSidedP(-1, 3)).toThrow(RangeError);
  });
});

describe('CH3 blind sheet', () => {
  const rubric = loadRubricWording();
  const pairs = CASES.map((c) => ({
    caseId: c.item.id,
    request: c.item.requestText,
    item: { shape: c.item.shape, language: c.item.language, title: c.item.title, codePoints: c.preparedCodePoints },
    keyPoints: c.keyPoints.map((key) => key.text),
    answers: { S3: `S3-ANSWER ${c.item.id}`, today: `TODAY-ANSWER ${c.item.id}` },
  }));

  function fill(sheet: BlindSheet, sides: Readonly<Record<string, { A: string; B: string }>>, s3Wins: number, ties = 0): BlindSheet {
    const copy = JSON.parse(JSON.stringify(sheet)) as BlindSheet;
    copy.entries.forEach((entry, index) => {
      entry.labels = { A: 'usable', B: 'good' };
      const s3Side = sides[entry.caseId]?.A === 'S3' ? 'A' : 'B';
      entry.preference = index < ties ? 'tie' : index < ties + s3Wins ? s3Side : s3Side === 'A' ? 'B' : 'A';
    });
    return copy;
  }

  it('hides the arm: no arm name, random sides under a per-run seed kept only in the key', () => {
    const { sheet, key } = buildBlindSheet(pairs, { planDigest: 'p', rubric, seed: 'seed-one' });
    const text = JSON.stringify(sheet);
    expect(text).not.toMatch(/"S3"|"today"|seed-one/u);
    expect(key.seed).toBe('seed-one');
    for (const entry of sheet.entries) {
      const side = key.sides[entry.caseId] as { A: string; B: string };
      expect(entry.answers[side.A === 'S3' ? 'A' : 'B']).toBe(`S3-ANSWER ${entry.caseId}`);
      expect(entry.labels).toEqual({ A: null, B: null });
    }
    const firsts = Object.values(key.sides).filter((side) => side.A === 'S3').length;
    expect(firsts).toBeGreaterThan(4);
    expect(firsts).toBeLessThan(CASES.length - 4);
    expect(sheet.entries.map((e) => e.caseId)).not.toEqual(CASES.map((c) => c.item.id));
    const other = buildBlindSheet(pairs, { planDigest: 'p', rubric, seed: 'seed-two' });
    expect(other.key.sides).not.toEqual(key.sides);
    expect(buildBlindSheet(pairs, { planDigest: 'p', rubric }).key.seed).not.toBe(buildBlindSheet(pairs, { planDigest: 'p', rubric }).key.seed);
  });

  it('scores the preference with the one-sided binomial test over >= 25 non-tie pairs', () => {
    const { sheet, key } = buildBlindSheet(pairs, { planDigest: 'p', rubric, seed: 's' });
    const win = scoreFilledSheet(fill(sheet, key.sides, 22, 4), key);
    expect(win).toMatchObject({ ok: true, s3Wins: 22, todayWins: 6, ties: 4, nonTies: 28, pass: true });
    const weak = scoreFilledSheet(fill(sheet, key.sides, 16, 4), key);
    expect(weak).toMatchObject({ ok: true, s3Wins: 16, nonTies: 28, pass: false });
    const fewPairs = scoreFilledSheet(fill(sheet, key.sides, 24, 8), key);
    expect(fewPairs).toMatchObject({ ok: true, s3Wins: 24, nonTies: 24, pass: false });
    expect(fewPairs.ok && fewPairs.reason).toMatch(/only 24 non-tie pairs/u);
  });

  it('refuses an incomplete sheet, an edited answer and a foreign key', () => {
    const { sheet, key } = buildBlindSheet(pairs, { planDigest: 'p', rubric, seed: 's' });
    const filled = fill(sheet, key.sides, 22);
    const incomplete = JSON.parse(JSON.stringify(filled)) as BlindSheet;
    (incomplete.entries[3] as BlindSheet['entries'][number]).preference = null;
    expect(scoreFilledSheet(incomplete, key)).toMatchObject({ ok: false });
    const edited = JSON.parse(JSON.stringify(filled)) as BlindSheet & { entries: { answers: { A: string } }[] };
    (edited.entries[0] as { answers: { A: string } }).answers.A = 'changed';
    expect(scoreFilledSheet(edited, key)).toMatchObject({ ok: false });
    const foreign = buildBlindSheet(pairs, { planDigest: 'p', rubric, seed: 'other' }).key;
    expect(scoreFilledSheet(filled, foreign)).toMatchObject({ ok: false });
  });
});

